assert.throws(()=>buildRequests(styled,[{blockId:'styled',after:'good BOLD good'}]),/định dạng/);
assert.equal(buildRequests(styled,[{blockId:'styled',after:'bad BOLD good'}]).length,3);
const bold=[{id:'bold',startIndex:1,text:'see OLD now',styles:[{offset:0,length:4,style:{}},{offset:4,length:3,style:{bold:true}},{offset:7,length:4,style:{}}]}];
assert.equal(buildRequests(bold,[{blockId:'bold',after:'see NEW now'}])[2].updateTextStyle.textStyle.bold,true);

